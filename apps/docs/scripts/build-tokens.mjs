// Writes the eoria tokens as CSS custom properties so the docs site is styled
// by the same values the native components use. Runs before every build.
import { writeFile, mkdir } from 'node:fs/promises'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { presets, createThemes } from '@eoria/core/tokens'

const app = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const out = resolve(app, 'src/styles/tokens.css')

const kebab = (s) => s.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase())

/** Control heights, stroke, shadow and fonts of a preset as custom properties. */
function shapeLines(preset) {
  const out = []
  for (const [k, v] of Object.entries(preset.control)) out.push(`  --control-${k}: ${v}px;`)
  out.push(`  --stroke: ${preset.stroke}px;`)
  out.push(`  --stroke-color: ${preset.stroke ? 'var(--color-border)' : 'transparent'};`)
  out.push(`  --field-border: ${preset.stroke ? 'var(--color-input)' : 'transparent'};`)
  const { opacity, radius, offset } = preset.shadow
  out.push(
    `  --shadow-elevated: 0 ${offset * 2}px ${radius * 2}px rgba(0, 0, 0, ${opacity}), 0 1px 3px rgba(0, 0, 0, ${opacity / 2});`,
  )
  out.push(`  --font-body: ${preset.font.body?.web ?? 'var(--font)'};`)
  // Headings without a family of their own follow the body, as `headingFont` does natively.
  out.push(`  --font-heading: ${preset.font.heading?.web ?? 'var(--font-body)'};`)
  return out
}
const lines = ['/* Generated by scripts/build-tokens.mjs. Do not edit. */']

const { light } = createThemes(presets.zinc)
lines.push(':root {')
for (const [k, v] of Object.entries(light.space)) lines.push(`  --space-${k}: ${v}px;`)
for (const [k, v] of Object.entries(light.radius)) lines.push(`  --radius-${k}: ${v}px;`)
for (const [k, v] of Object.entries(light.fontSize)) lines.push(`  --text-${k}: ${v}px;`)
for (const [k, v] of Object.entries(light.lineHeight)) lines.push(`  --leading-${k}: ${v}px;`)
for (const [k, v] of Object.entries(light.fontWeight)) lines.push(`  --weight-${k}: ${v};`)
lines.push(...shapeLines(presets.zinc))
// Swatches for the preset picker, independent of the active preset: primary colour and
// the preset's md radius, so the swatch shape hints at the look.
for (const [name, preset] of Object.entries(presets)) {
  lines.push(`  --swatch-${name}-light: ${preset.light.primary};`)
  lines.push(`  --swatch-${name}-dark: ${preset.dark.primary};`)
  lines.push(`  --swatch-${name}-radius: ${preset.radius.md}px;`)
}
lines.push('}')

// Shape per preset, then colours per preset and mode.
for (const [name, preset] of Object.entries(presets)) {
  lines.push(`:root[data-preset='${name}'] {`)
  for (const [k, v] of Object.entries(preset.radius)) lines.push(`  --radius-${k}: ${v}px;`)
  for (const [k, v] of Object.entries(preset.fontWeight)) lines.push(`  --weight-${k}: ${v};`)
  lines.push(...shapeLines(preset))
  lines.push('}')
  for (const mode of ['light', 'dark']) {
    lines.push(`:root[data-preset='${name}'][data-mode='${mode}'] {`)
    for (const [k, v] of Object.entries(preset[mode])) lines.push(`  --color-${kebab(k)}: ${v};`)
    lines.push('}')
  }
}

await mkdir(dirname(out), { recursive: true })
await writeFile(out, lines.join('\n') + '\n')
console.log(`docs: wrote tokens for ${Object.keys(presets).length} presets`)
