// Writes the eoria tokens as CSS custom properties so the docs site is styled
// by the same values the native components use. Runs before every build.
import { writeFile, mkdir } from 'node:fs/promises'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { colorPresets, createThemes } from '@eoria/core/tokens'

const app = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const out = resolve(app, 'src/styles/tokens.css')

const kebab = (s) => s.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase())
const lines = ['/* Generated by scripts/build-tokens.mjs. Do not edit. */']

const { light } = createThemes(colorPresets.zinc)
lines.push(':root {')
for (const [k, v] of Object.entries(light.space)) lines.push(`  --space-${k}: ${v}px;`)
for (const [k, v] of Object.entries(light.radius)) lines.push(`  --radius-${k}: ${v}px;`)
for (const [k, v] of Object.entries(light.fontSize)) lines.push(`  --text-${k}: ${v}px;`)
for (const [k, v] of Object.entries(light.lineHeight)) lines.push(`  --leading-${k}: ${v}px;`)
for (const [k, v] of Object.entries(light.fontWeight)) lines.push(`  --weight-${k}: ${v};`)
// Swatch colours for the preset picker, independent of the active preset.
for (const [name, preset] of Object.entries(colorPresets)) {
  lines.push(`  --swatch-${name}-light: ${preset.light.primary};`)
  lines.push(`  --swatch-${name}-dark: ${preset.dark.primary};`)
}
lines.push('}')

for (const [name, preset] of Object.entries(colorPresets)) {
  for (const mode of ['light', 'dark']) {
    lines.push(`:root[data-preset='${name}'][data-mode='${mode}'] {`)
    for (const [k, v] of Object.entries(preset[mode])) lines.push(`  --color-${kebab(k)}: ${v};`)
    lines.push('}')
  }
}

await mkdir(dirname(out), { recursive: true })
await writeFile(out, lines.join('\n') + '\n')
console.log(`docs: wrote tokens for ${Object.keys(colorPresets).length} presets`)
